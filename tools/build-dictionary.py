"""Builds js/dictionary.js from an open Tamil word-frequency list plus a hand-made supplement.

Source list: hermitdave/FrequencyWords (content/2018/ta/ta_full.txt), built from
OpenSubtitles 2018, licensed CC BY-SA 4.0.

Usage: python3 tools/build-dictionary.py path/to/ta_full.txt
"""
import json
import re
import sys
import unicodedata
from pathlib import Path

TAMIL_WORD = re.compile(r"^[஀-௿]+$")
ROOT = Path(__file__).resolve().parent.parent

freq_path = Path(sys.argv[1])
words = []
for line in freq_path.read_text(encoding="utf-8").splitlines():
    parts = line.split()
    if len(parts) == 2 and TAMIL_WORD.match(parts[0]):
        words.append(unicodedata.normalize("NFC", parts[0]))  # file is already sorted by frequency

supplement = [
    unicodedata.normalize("NFC", w.strip())
    for w in (ROOT / "tools" / "supplement.txt").read_text(encoding="utf-8").splitlines()
    if w.strip() and not w.startswith("#")
]

# Supplement words are common, so give them a good rank: slot them in after the top 1,500.
seen = set()
ordered = []
for w in words[:1500] + supplement + words[1500:]:
    if w not in seen:
        seen.add(w)
        ordered.append(w)

out = ROOT / "js" / "dictionary.js"
out.write_text(
    "// Generated by tools/build-dictionary.py. Do not edit by hand.\n"
    "// Tamil words, most common first. Word list: FrequencyWords (OpenSubtitles 2018), CC BY-SA 4.0.\n"
    "window.TAMIL_WORDS = " + json.dumps(" ".join(ordered), ensure_ascii=False) + ".split(\" \");\n",
    encoding="utf-8",
)
print(f"{len(ordered)} words ({len(supplement)} from supplement) -> {out} ({out.stat().st_size // 1024} KB)")
